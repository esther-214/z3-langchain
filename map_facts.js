function reshapeArray(flatArray, rows, cols) {
  if (flatArray.length !== rows * cols) {
    throw new Error("Invalid dimensions: The array length does not match the specified dimensions.");
  }

  let reshapedArray = [];
  for (let i = 0; i < rows; i++) {
    reshapedArray.push(flatArray.slice(i * cols, (i + 1) * cols));
  }

  return reshapedArray;
}

