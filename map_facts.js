let db = new sqlite3.Database("map.db");

db.serialize(() => {
  db.run("CREATE TABLE coordinates (coordinate TEXT, value TEXT)");

  let stmt = db.prepare("INSERT INTO coordinates VALUES (?, ?)");

  for (let i = 0; i < array2D.length; i++) {
    for (let j = 0; j < array2D[i].length; j++) {
      let coordinate = `(${i},${j})`;
      let value = array2D[i][j];
      stmt.run(coordinate, value);
    }
  }

  stmt.finalize();

  db.each("SELECT coordinate, value FROM coordinates", (err, row) => {
    if (err) {
      console.error(err.message);
    }
    console.log(`${row.coordinate}: ${row.value}`);
  });
});

db.close();
